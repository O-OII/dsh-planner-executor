/* Paste this async expression in browser DevTools on demo/index.html?view=settings&lang=en.
 * Runs the real React form/overlay against synthetic Settings only; never calls models.
 */
async () => {
  const results = [];
  const wait = () => new Promise(resolve => setTimeout(resolve, 40));
  const assert = (name, condition) => { results.push({ name, pass: Boolean(condition) }); if (!condition) throw new Error(name); };
  const panelNS = 'subagent-activity', routeNS = 'planner-executor-routing';
  const card = ns => document.querySelector(`[data-settings-card="${ns}"]`);
  const field = (ns, name) => card(ns).querySelector(`[name="${name}"]`);
  const save = ns => card(ns).querySelector('[data-settings-save]');
  const discard = ns => card(ns).querySelector('[data-settings-discard]');
  const set = async (element, value) => {
    if (!element) throw new Error('Missing test input');
    const prototype = element.tagName === 'SELECT' ? HTMLSelectElement.prototype : HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, value);
    element.dispatchEvent(new Event('input', { bubbles: true }));
    element.dispatchEvent(new Event('change', { bubbles: true }));
    await wait();
  };
  const click = async element => { if (!element || element.matches(':disabled')) throw new Error('Missing/disabled test action'); element.click(); await wait(); };
  const confirmed = () => card(routeNS).querySelector('[data-settings-confirmed-routing]')?.getAttribute('data-settings-confirmed-routing');
  for (let i = 0; i < 100 && (!card(routeNS) || field(routeNS, 'targetRoute.model')?.value !== 'execution-model'); i++) await wait();
  const demo = window.activityDemo;
  assert('official bundle configuration slot mounts both cards', Boolean(card(panelNS) && card(routeNS)));
  assert('opening page and catalog read perform no writes', demo.writes.length === 0);
  assert('initial status is Host-confirmed OFF', confirmed() === 'off');
  assert('clean cards cannot save', save(panelNS).disabled && save(routeNS).disabled);
  assert('catalog assists through exact provider id options', [...card(routeNS).querySelectorAll('datalist option')].some(option => option.value === 'example-executor'));
  assert('provider ids are not replaced with display names', field(routeNS, 'targetRoute.provider').value === 'example-executor');
  assert('only custom setup owns a masked write-only key input', document.querySelector('[name="custom.apiKey"]').type === 'password' && document.querySelector('[name="custom.apiKey"]').autocomplete === 'new-password' && !card(routeNS).querySelector('input[type=password]'));
  assert('custom model setup is available without automatic provider writes', document.querySelector('[data-custom-status]').dataset.customStatus === 'ready');
  await set(field(routeNS, 'targetRoute.model'), 'draft-target');
  assert('typing stages a draft without writing', demo.writes.length === 0 && save(routeNS).disabled === false);
  await set(document.querySelector('[name=pageLanguage]'), 'zh-CN');
  assert('page language immediately translates headings', card(routeNS).textContent.includes('主从协作'));
  assert('switching page language preserves unsaved route', field(routeNS, 'targetRoute.model').value === 'draft-target');
  assert('page language preview never writes settings', demo.writes.length === 0);
  await set(document.querySelector('[name=pageLanguage]'), 'en');
  demo.changeLocale('zh'); await wait();
  assert('DSH locale update does not clear draft', field(routeNS, 'targetRoute.model').value === 'draft-target');
  demo.changeLocale('en'); await wait();
  await set(field(panelNS, 'locale'), 'en');
  await click(save(panelNS));
  assert('panel saves only panel namespace', demo.writes.length === 1 && demo.writes[0].ns === panelNS && Object.keys(demo.writes[0].patch).join() === 'locale');
  assert('independent panel save leaves route draft intact', field(routeNS, 'targetRoute.model').value === 'draft-target' && demo.configs[routeNS].targetRoute.model === 'execution-model');
  assert('saved panel receipt reaches Host authority', demo.configs[panelNS].locale === 'en');
  await click(field(routeNS, 'enabled'));
  assert('unsaved enable does not change confirmed state or overlay', confirmed() === 'off' && document.querySelector('[data-planner-routing-switch="off"]'));
  await click(save(routeNS));
  const write = demo.writes.at(-1);
  assert('route save submits the complete namespace in one patch', write.ns === routeNS && ['enabled', 'parentRoutes', 'targetRoute', 'locale'].every(key => Object.hasOwn(write.patch, key)));
  assert('route save includes the read revision', Number.isSafeInteger(write.revision) && write.revision >= 0);
  assert('save commits draft target without label conversion', demo.configs[routeNS].targetRoute.model === 'draft-target');
  assert('Host-confirmed ON appears in configuration card', confirmed() === 'on');
  assert('configuration save synchronizes overlay ON', Boolean(document.querySelector('[data-planner-routing-switch="on"]')));
  await set(field(routeNS, 'targetRoute.model'), 'bad model');
  assert('whitespace identifier blocks save', save(routeNS).disabled && Boolean(card(routeNS).querySelector('[data-settings-validation]')));
  await click(discard(routeNS));
  assert('discard restores last Host-confirmed target', field(routeNS, 'targetRoute.model').value === 'draft-target');
  const add = card(routeNS).querySelector('[data-settings-action="add-parent"]');
  await click(add);
  assert('parent condition can be added', Boolean(field(routeNS, 'parentRoutes.1.provider')));
  assert('incomplete parent row blocks save', save(routeNS).disabled);
  await set(field(routeNS, 'parentRoutes.1.provider'), 'another-planner');
  await set(field(routeNS, 'parentRoutes.1.model'), 'another-model');
  assert('complete second parent row validates', save(routeNS).disabled === false);
  await click([...card(routeNS).querySelectorAll('[data-settings-action="remove-parent"]')].at(-1));
  assert('parent condition can be removed', !field(routeNS, 'parentRoutes.1.provider'));
  await set(field(routeNS, 'targetRoute.model'), 'retained-conflict-draft');
  const writesBeforeConflict = demo.writes.length;
  demo.external(routeNS, { targetRoute: { provider: 'example-executor', model: 'external-target' } }); await wait();
  assert('external update preserves dirty draft', field(routeNS, 'targetRoute.model').value === 'retained-conflict-draft');
  assert('external update blocks stale save', save(routeNS).disabled && Boolean(card(routeNS).querySelector('[data-settings-review]')));
  assert('external update never replays write intent', demo.writes.length === writesBeforeConflict);
  assert('current Host details show external truth', card(routeNS).querySelector('[data-settings-host-value]').textContent.includes('external-target'));
  await click(card(routeNS).querySelector('[data-settings-review]'));
  assert('explicit review enables saving a retained valid draft', !save(routeNS).disabled && field(routeNS, 'targetRoute.model').value === 'retained-conflict-draft');
  await click(save(routeNS));
  assert('explicitly reviewed draft commits against latest revision', demo.configs[routeNS].targetRoute.model === 'retained-conflict-draft');
  demo.fail('settings/rejected');
  await click(field(routeNS, 'enabled')); await click(save(routeNS));
  assert('failed disabling keeps confirmed ON', confirmed() === 'on' && demo.configs[routeNS].enabled === true);
  assert('failed disabling keeps overlay ON', Boolean(document.querySelector('[data-planner-routing-switch="on"]')));
  assert('failed save shows error and retains OFF draft', Boolean(card(routeNS).querySelector('[data-settings-error]')) && field(routeNS, 'enabled').checked === false);
  demo.fail(null); await click(discard(routeNS));
  demo.setOverrides({ enabled: 'home' }); await wait();
  await click(field(routeNS, 'enabled')); await click(save(routeNS));
  assert('home overlay refusal is visible and disables saving', save(routeNS).disabled && Boolean(card(routeNS).querySelector('[data-settings-error]')));
  assert('home overlay refusal does not claim disabled success', confirmed() === 'on' && demo.configs[routeNS].enabled);
  assert('home overlay refusal retains unsaved draft', field(routeNS, 'enabled').checked === false);
  demo.setOverrides({}); await wait();
  await click(document.querySelector('[data-settings-read]')); await wait();
  if (card(routeNS).querySelector('[data-settings-review]')) await click(card(routeNS).querySelector('[data-settings-review]'));
  await click(discard(routeNS));
  demo.hold(); await click(field(routeNS, 'enabled')); await click(save(routeNS));
  assert('in-flight save disables duplicate submission', save(routeNS).disabled);
  demo.reconnect(); await wait(); demo.release(); await wait();
  assert('reconnect preserves unsaved OFF draft', field(routeNS, 'enabled').checked === false);
  assert('late old-generation response never fabricates OFF', confirmed() === 'on');
  assert('reconnect requires explicit draft review', save(routeNS).disabled && Boolean(card(routeNS).querySelector('[data-settings-review]')));
  // New-provider flow uses synthetic official namespace operations, never a network API.
  await click(discard(routeNS));
  await click(document.querySelector('[data-custom-reload]'));
  await set(document.querySelector('[name="custom.provider"]'), 'browser-demo-api');
  await set(document.querySelector('[name="custom.displayName"]'), 'Browser demo API');
  await set(document.querySelector('[name="custom.baseURL"]'), 'https://gateway.example/v1');
  await set(document.querySelector('[name="custom.models.0.id"]'), 'browser-demo-model');
  await set(document.querySelector('[name="custom.apiKey"]'), 'synthetic-key-not-real');
  const beforeProvider = demo.writes.length;
  assert('provider draft never writes before explicit Create', !demo.configs['llm-pi-ai'].providers['browser-demo-api']);
  await click(document.querySelector('[data-custom-create]')); await wait();
  assert('custom provider creates exact profile path through official mutate', demo.writes.length === beforeProvider + 1 && demo.writes.at(-1).ns === 'llm-pi-ai' && demo.writes.at(-1).ops[0].path.join('.') === 'providers.browser-demo-api');
  assert('API key stored separately and not in settings mutation', demo.keyWrites.at(-1)?.ref === 'BROWSER_DEMO_API_API_KEY' && !JSON.stringify(demo.writes).includes('synthetic-key-not-real'));
  assert('successful credential save clears masked field', document.querySelector('[name="custom.apiKey"]').value === '' && document.querySelector('[data-custom-status]').dataset.customStatus === 'saved');
  assert('created model refreshes role choices', [...card(routeNS).querySelectorAll('[name="targetRoute.catalogChoice"] option')].some(option => option.value === JSON.stringify(['browser-demo-api', 'browser-demo-model'])));
  assert('provider creation does not automatically enable or change routing', demo.configs[routeNS].targetRoute.model !== 'browser-demo-model');
  await set(field(routeNS, 'targetRoute.catalogChoice'), JSON.stringify(['browser-demo-api', 'browser-demo-model']));
  assert('role selection uses exact created provider and model', field(routeNS, 'targetRoute.provider').value === 'browser-demo-api' && field(routeNS, 'targetRoute.model').value === 'browser-demo-model');
  await click(save(routeNS));
  assert('separate role save commits newly created executor', demo.configs[routeNS].targetRoute.provider === 'browser-demo-api');
  demo.setWritable(false); await wait();
  assert('readonly profile disables both save controls', save(panelNS).disabled && save(routeNS).disabled);
  assert('readonly profile disables editable fields', field(panelNS, 'locale').matches(':disabled') && field(routeNS, 'targetRoute.model').matches(':disabled'));
  assert('readonly profile explains refusal', /read.only|not allow|不可写|不允许/i.test(card(panelNS).textContent));
  return { scope: 'Synthetic public Settings authority; actual production React configuration page and overlay. NOT live DSH navigation/transport.', count: results.length, results };
}
